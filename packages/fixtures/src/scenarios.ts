export const seededScenarioMap = new Map(
  seededScenarios.map((scenario) => [scenario.id, scenario]),
);

export const getSeededScenario = (
  scenarioId: string,
): MergeRequestScenarioInput | null => seededScenarioMap.get(scenarioId) ?? null;

export const analyzeSeededScenario = (scenarioId: string) => {
  const scenario = getSeededScenario(scenarioId);
  if (!scenario) {
    throw new Error(`Unknown ArcGuard scenario: ${scenarioId}`);
  }

  return analyzeMergeRequest(scenario);
};
